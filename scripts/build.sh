# ── Step 2: Refresh version ──────────────────────────────────────────────────
# src/rev80/_version.py is generated by setuptools_scm from the current git
# state (tags, describe) whenever the local package is (re)installed — a
# quick --no-deps reinstall regenerates it fresh here so the frozen binary
# always embeds the correct tag, even if it's been a while since the last
# `pip install -e .` (e.g. a tag was applied after that).

echo "[2/5] Reinstall package with pip."
#echo "Activate venv..."
#source .venv/Scripts/activate # user must activate their venv.
echo "pip install -e . -q" 
pip install -e . -q --no-deps
VERSION=$(python -c "import rev80; print(rev80.__version__)")
echo "Version: $VERSION"
echo

# ── Step 3: Collect PicoScope DLLs ──────────────────────────────────────────
if [[ "$STEP" == "all" || "$STEP" == "dlls" ]]; then
    echo "[3/5] Collecting PicoScope DLLs..."
    python build/collect_pico_dlls.py
    echo
fi

# ── Step 4: PyInstaller ──────────────────────────────────────────────────────
if [[ "$STEP" == "all" || "$STEP" == "pyinstaller" ]]; then
    echo "[4/5] Building executable with PyInstaller..."

    # Kill any running instance so Windows releases file locks on output DLLs
    taskkill /f /im rev80.exe >/dev/null 2>&1 || true

    # Wipe previous output cleanly — pyinstaller --noconfirm skips locked files
    if [[ -d dist/rev80 ]]; then
        echo "Cleaning previous build output..."
        rm -rf dist/rev80
    fi

    python -m PyInstaller build/rev80.spec --noconfirm $PYINSTALLER_CLEAN
    echo
fi

# ── Step 5: Inno Setup ───────────────────────────────────────────────────────
if [[ "$STEP" == "all" || "$STEP" == "installer" ]]; then
    echo "[5/5] Creating installer with Inno Setup..."
    "$ISCC" installer/rev80.iss
    echo
fi

echo "============================================================"
echo "  Build complete."
echo "  Installer: installer/Output/Rev80Setup-*.exe"
echo "============================================================"
