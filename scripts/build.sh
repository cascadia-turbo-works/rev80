#!/usr/bin/env bash
# build.sh  —  Full Rev80 Windows build pipeline (runs in Git Bash)
#
# Prerequisites:
#   - 64-bit Python 3.10+ in PATH
#   - pip install pyinstaller
#   - PicoSDK DLLs available via one of:
#       a) PicoSDK installed on the build machine (auto-detected via registry)
#       b) PICO_DLL_DIR env var pointing at a directory with ps4000a.dll + picoipp.dll
#       c) vendor/pico/ in project root (gitignored) containing the same DLLs
#      Source: C:\Program Files\Pico Technology\SDK\lib\ on any PicoSDK install
#   - Inno Setup 6.x installed
#
# Usage:
#   ./build.sh              # full build: DLLs + PyInstaller + Inno Setup
#   ./build.sh dlls         # DLL collection only
#   ./build.sh pyinstaller  # PyInstaller only (skip DLL collection)
#   ./build.sh installer    # Inno Setup only (requires dist/ to exist)

set -euo pipefail

STEP="${1:-all}"
# Pass --clean to force a full PyInstaller cache wipe (slow but safe after
# adding new dependencies or if the build cache seems corrupt):
#   ./build.sh all clean
PYINSTALLER_CLEAN=""
for arg in "$@"; do
    [[ "$arg" == "clean" ]] && PYINSTALLER_CLEAN="--clean"
done

# Locate iscc.exe — try PATH first, then common install locations.
# $LOCALAPPDATA is a Windows-style path in Git Bash; convert with cygpath.
find_iscc() {
    if command -v iscc &>/dev/null; then
        echo "iscc"
        return
    fi
    local localappdata_unix=""
    if [[ -n "${LOCALAPPDATA:-}" ]]; then
        localappdata_unix=$(cygpath "$LOCALAPPDATA" 2>/dev/null || echo "")
    fi
    local candidates=(
        "$localappdata_unix/Programs/Inno Setup 6/iscc.exe"
        "/c/Program Files (x86)/Inno Setup 6/iscc.exe"
        "/c/Program Files/Inno Setup 6/iscc.exe"
    )
    for c in "${candidates[@]}"; do
        if [[ -n "$c" && -f "$c" ]]; then
            echo "$c"
            return
        fi
    done
    echo ""
}

echo
echo "============================================================"
echo "  Rev80 Windows Build Pipeline"
echo "============================================================"
echo

# ── Preflight checks ─────────────────────────────────────────────────────────
if [[ "$STEP" == "all" || "$STEP" == "installer" ]]; then
    ISCC="$(find_iscc)"
    if [[ -z "$ISCC" ]]; then
        echo "ERROR: iscc.exe not found. Install Inno Setup 6 from https://jrsoftware.org/isinfo.php"
        exit 1
    fi
    echo "Found Inno Setup: $ISCC"
    echo
fi

